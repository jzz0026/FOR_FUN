out_dir = "/project/small_grains/Jinlie.Zhou/for_fun/youtube_video/audio"
os.makedirs(out_dir, exist_ok=True)

def fmt_srt_time(ms):
    s, ms = divmod(int(ms), 1000)
    m, s = divmod(s, 60)
    h, m = divmod(m, 60)
    return f"{h:02d}:{m:02d}:{s:02d},{ms:03d}"

async def main():
    meta = []
    for sid, chapter, text in SCENES:
        mp3_path = os.path.join(out_dir, f"{sid}.mp3")
        comm = edge_tts.Communicate(text, VOICE, rate=RATE)
        sub_events = []
        with open(mp3_path, "wb") as f:
            async for chunk in comm.stream():
                if chunk["type"] == "audio":
                    f.write(chunk["data"])
                elif chunk["type"] in ("WordBoundary", "SentenceBoundary"):
                    sub_events.append({
                        "type": chunk["type"],
                        "offset_ms": chunk["offset"] / 10000.0,
                        "duration_ms": chunk["duration"] / 10000.0,
                        "text": chunk["text"],
                    })
        meta.append({"id": sid, "chapter": chapter, "text": text, "mp3": mp3_path, "events": sub_events})
        print(f"Synthesized {sid}: {len(sub_events)} timing events")
    with open(os.path.join(out_dir, "tts_meta.json"), "w", encoding="utf-8") as f:
        json.dump(meta, f, ensure_ascii=False, indent=2)
    print("All 13 scenes synthesized.")

asyncio.run(main())
